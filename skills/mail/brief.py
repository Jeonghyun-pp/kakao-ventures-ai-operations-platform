"""슬랙에 올릴 **한 문단 요약** — 사람이 쓰던 말투를 그대로 쓴다.

## 왜 요약이 필요한가

맨 위 글은 훑는 자리다. 메일 앞 400자를 그대로 붙이면 인사말만 보이고
정작 무엇을 묻는지는 안 보인다. 실측(BIXPO): 400자가 전부 행사 소개였고
"투자자 30인 초청 · 9/16 마감" 이라는 핵심은 그 뒤에 있었다.

## 말투는 지어내지 않았다 — 실제 기록에서 뽑았다

#Squad-비플랜 채널에서 사람이 반년간 써온 형식이 뚜렷했다:

    "에어월렉스에서 VC 파트너십 제안이 왔습니다. 포트폴리오사 해외 법인계좌 개설·
     환전 수수료 쪽 혜택인데, 영업 메일이긴 하지만 혹시 관심 있으실까 싶어 공유드립니다."

    "Example Legal스가 운영하는 창업진흥원 프리팁스 2차 모집(~8/10, 30개사 내외,
     최대 1억원 사업화 자금)에 비수도권 소재 3년 이내 창업기업을 추천해 달라는 요청입니다."

세 가지가 항상 있었다 — 발신 주체를 앞에, 숫자·날짜·조건을 살려서, 자기 판단을 미리.
"""
from __future__ import annotations

from kvlib import Fetched, constraints
from kv_transport import claude

_SYSTEM = (
    "너는 카카오벤처스 투자팀 인턴이다. 공용 메일함에 온 메일을 팀 슬랙방에 공유하며 "
    "한 문단 요약을 쓴다. 인사말이나 머리말 없이 요약 문장만 출력한다."
)

_GUIDE = """\
아래 메일을 팀 슬랙방에 공유할 **한 문단 요약**으로 써라.

## 형식
[발신 주체]에서/가 [무엇]이 왔습니다/요청입니다. [핵심 조건·숫자·날짜]. [판단 유보].

## 반드시 지킬 것
- 두세 문장. 300자 이내.
- **발신 주체를 맨 앞에** 놓는다. "OO에서", "OO가 운영하는".
- **숫자·날짜·마감·금액·인원을 살린다.** 이게 사람이 결정할 때 보는 것이다.
- 홍보성·영업성이면 그렇다고 **미리 말한다** — "영업 메일이긴 하지만",
  "홍보성이긴 하지만", "행사성이긴 하지만".
- 우리에게 **무엇을 해달라는 것인지** 한 번은 분명히 적는다.
- 존댓말. "~습니다" 로 끝낸다.

## 하지 말 것
- 메일에 없는 내용을 지어내지 마라. 모르면 안 쓴다.
- "안녕하세요", "공유드립니다" 로 시작하지 마라. 본론부터.
- 이모지를 쓰지 마라.
- 마크다운 제목·불릿을 쓰지 마라. 줄글 한 문단이다.

## 실제 예시
에어월렉스에서 VC 파트너십 제안이 왔습니다. 포트폴리오사 해외 법인계좌 개설·환전 수수료 쪽 혜택인데, 영업 메일이긴 하지만 혹시 관심 있으실까 싶어 공유드립니다.
Example Legal스가 운영하는 창업진흥원 프리팁스 2차 모집(~8/10, 30개사 내외, 최대 1억원 사업화 자금)에 비수도권 소재 3년 이내 창업기업을 추천해 달라는 요청입니다.
예술경영지원센터에서 8/21 아트스타트업데이 투자상담회 투자자 섭외 요청이 왔는데, 행사성이긴 하지만 관심 있으실까 싶어 공유드립니다.
"""


def write(msg: dict) -> Fetched:
    """메일 하나 → 요약 한 문단. 실패해도 계획 전체를 세우지 않는다 — 미상을 돌려준다."""
    cap = constraints.get("gmail.body_chars_for_judge")
    prompt = (f"{_GUIDE}\n\n# 메일\n"
              f"발신: {msg.get('sender_raw') or msg.get('sender')}\n"
              f"제목: {msg.get('subject')}\n"
              f"본문:\n{(msg.get('body') or '')[:cap]}\n")
    try:
        raw = claude.run_session(prompt, system=_SYSTEM)
    except claude.SessionError as e:
        return Fetched.unknown(f"claude:{e}")

    # 🔴 머리말·불릿·코드펜스를 걷어낸다. 그래도 비면 미상이다 —
    #    빈 문자열을 요약이라고 내놓으면 슬랙에 제목만 덩그러니 올라간다.
    lines = [ln.strip() for ln in raw.splitlines()
             if ln.strip() and not ln.strip().startswith(("#", "```", "-", "*", "•"))]
    text = " ".join(lines).strip()
    if len(text) < 20:
        return Fetched.unknown(f"요약이 너무 짧다: {text[:40]!r}")
    return Fetched.measured(text[:400])
